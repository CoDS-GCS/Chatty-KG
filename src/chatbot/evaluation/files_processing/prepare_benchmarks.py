import json
import time

import requests

kg_related_variables = {"yago": ("http://206.12.95.86:8892/sparql", "../data/yago_e11_20_5_original.json"),
                        "dblp": ("http://206.12.95.86:8894/sparql", "../data/dblp_e11_20_5_original.json"),
                        "dbpedia": ("http://206.12.95.86:8890/sparql", "../data/dbpedia_e11_20_5_original.json"),
                        "wikidata": ("https://query.wikidata.org/sparql", "../data/wikidata_subgraph_summarized_20_5_simplified.json"),
                        }


def evaluate_SPARQL_query_wikidata(endpoint, query: str):
    headers = {"Accept": "application/sparql-results+json"}
    query_response = requests.get(endpoint, params={"query": query}, headers=headers)
    if query_response.status_code in [414]:
        return '{"head":{"vars":[]}, "results":{"bindings": []}, "status":414 }'
    return query_response.text

def evaluate_SPARQL_query(endpoint, query):
    payload = {
        "default-graph-uri": "",
        "query": query,
        "format": "application/json",
        "CXML_redir_for_subjs": "121",
        "CXML_redir_for_hrefs": "",
        "timeout": "40000",
        "debug": "on",
        "run": "+Run+Query+",
    }
    query_response = requests.get(endpoint, params=payload)
    if query_response.status_code in [414]:
        return '{"head":{"vars":[]}, "results":{"bindings": []}, "status":414 }'
    return query_response.text

# Take a file generated by Chatty-Gen and generate two benchmark files: Dialogue and Standalone
if __name__ == '__main__':
    dataset = 'dblp'
    endpoint, dataset_file = kg_related_variables[dataset]
    id = 0
    with open(dataset_file) as json_file:
        data = json.load(json_file)

    dialogue_output, standalone_output = list(), list()
    id = 0
    for instance in data['data']:
        for dialogue, standalone, query in zip(instance['dialogue'], instance['original'], instance['queries']):
            if dataset == "wikidata":
                result = evaluate_SPARQL_query_wikidata(endpoint, query)
                time.sleep(2)
            else:
                result = evaluate_SPARQL_query(endpoint, query)
            result_json = json.loads(result)

            dialogue_instance = {'id': id, 'question': dialogue, 'answers': [result_json]}
            standalone_instance = {'id': id, 'question': standalone, 'answers': [result_json]}
            id += 1
            dialogue_output.append(dialogue_instance)
            standalone_output.append(standalone_instance)


    dataset_id = dataset_file.split('/')[-1]
    dot_index = dataset_id.find('.')
    dataset_id = dataset_id[:dot_index]

    # Dialogue benchmark:
    with open(f'{dataset_id}_dialogue.json', 'w') as rfobj:
        dataset = {"dataset": {"id": f'{dataset_id}_dialogue'}, "questions": dialogue_output}
        json.dump(dataset, rfobj, indent=4)
        rfobj.write('\n')

    # Standalone benchmark:
    with open(f'{dataset_id}_standalone.json', 'w') as rfobj:
        dataset = {"dataset": {"id": f"{dataset_id}_standalone"}, "questions": standalone_output}
        json.dump(dataset, rfobj, indent=4)
        rfobj.write('\n')